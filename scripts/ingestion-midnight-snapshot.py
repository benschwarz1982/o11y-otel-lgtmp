# --- Prometheus remote_write: hand-rolled protobuf wire format ---
# (WriteRequest{repeated TimeSeries}, TimeSeries{repeated Label, repeated
# Sample}, Label{string name, value}, Sample{double value, int64 timestamp})
# - simple enough to encode directly, no compiled .proto needed.


def _varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def _tag(field_no, wire_type):
    return _varint((field_no << 3) | wire_type)


def _encode_string_field(field_no, s):
    b = s.encode("utf-8")
    return _tag(field_no, 2) + _varint(len(b)) + b


def _encode_label(name, value):
    return _encode_string_field(1, name) + _encode_string_field(2, value)


def _encode_sample(value, timestamp_ms):
    body = _tag(1, 1) + struct.pack("<d", value)
    body += _tag(2, 0) + _varint(timestamp_ms)
    return body


def _encode_timeseries(labels, samples):
    body = b""
    for name, value in labels:
        lbl = _encode_label(name, value)
        body += _tag(1, 2) + _varint(len(lbl)) + lbl
    for val, ts in samples:
        smp = _encode_sample(val, ts)
        body += _tag(2, 2) + _varint(len(smp)) + smp
    return body


def _encode_write_request(all_labels_samples):
    body = b""
    for labels, samples in all_labels_samples:
        ts_bytes = _encode_timeseries(labels, samples)
        body += _tag(1, 2) + _varint(len(ts_bytes)) + ts_bytes
    return body


# --- Minimal pure-Python Snappy encoder (literal-only, no back- ---
# references - compression ratio doesn't matter here, only avoiding a
# C-extension/pip dependency for the CronJob's container image;
# verified live to round-trip correctly via the real Snappy decoder).


def _snappy_literal_tag(length):
    n = length - 1
    if n < 60:
        return bytes([n << 2])
    nbytes = (n.bit_length() + 7) // 8
    return bytes([(59 + nbytes) << 2]) + n.to_bytes(nbytes, "little")


def _snappy_compress(data: bytes) -> bytes:
    out = bytearray()
    out += _varint(len(data))
    chunk_size = 65536
    for i in range(0, len(data), chunk_size) or [0]:
        chunk = data[i : i + chunk_size]
        if chunk:
            out += _snappy_literal_tag(len(chunk))
            out += chunk
    return bytes(out)


_TENANT_ID_RE = re.compile(r"^[a-z0-9-]+$")


def _instant_query(promql: str, tenant_label: str) -> dict:
    """Runs one Mimir instant query (a single evaluation as of now, NOT
    a query_range call - Mimir's/Prometheus's `/api/v1/query` endpoint
    evaluates any valid PromQL expression as of one instant, including
    one containing a range-vector selector like `increase(x[1h])`; it
    is not limited to plain instant-vector expressions the way the
    endpoint's own name might suggest). Sums across every series
    sharing a tenant_label value - the outer `sum by (...)` in the
    PromQL itself already does this (see query_since_midnight()), so in
    practice each tenant appears as at most one result row already;
    this Python-side sum is just defense in depth."""
    url = f"{MIMIR_QUERY_URL}?query={urllib.parse.quote(promql)}"
    req = urllib.request.Request(url, headers={"X-Scope-OrgID": ANONYMOUS_ORG_ID})
    with urllib.request.urlopen(req, timeout=15) as resp:
        payload = json.load(resp)
    values = {}
    for series in payload["data"]["result"]:
        tenant = series["metric"].get(tenant_label)
        if tenant:
            values[tenant] = values.get(tenant, 0.0) + float(series["value"][1])
    return values


def query_since_midnight(metric_name: str, tenant_label: str, elapsed_seconds: int, only_tenant: str | None = None) -> dict:
    """Returns {tenant_id: real increase since `elapsed_seconds` ago}
    for one signal's raw counter - the actual thing this script's own
    enforcement decision (main()) and the pushed SINCE_MIDNIGHT_METRIC
    gauge (read directly by the dashboard/alert) are both based on.

    NFR-05 second pre-test audit round found three further confirmed
    bugs in the first round's own fix (a hand-rolled Python "day-start
    snapshot" + incremental accumulator, replaced entirely by this
    function):

    1. A tenant already ingesting BEFORE this script's own first look
       at it (e.g. onboarded and immediately active, or the CronJob
       itself was down for a while and its first run of a new day
       happens well after actual local midnight) had that pre-existing
       usage simply excluded - the accumulator always started counting
       from 0 at first sight, with no way to know what came before.
       `increase(metric[Xs])` has no such blind spot: Mimir has ALWAYS
       been storing this counter's real samples regardless of whether
       this script itself was running or had looked at that tenant
       before, so a window computed from the actual wall-clock seconds
       since real local midnight (not "since this script first saw
       this tenant today") correctly picks up everything that already
       happened - a late first daily run genuinely gets the FULL
       calendar day's usage, not just what happened after it finally
       ran.
    2. Counter resets across MULTIPLE instances of the same signal
       (e.g. two distributor pods) were invisible: this script queried
       Mimir with a `sum by (tenant)` already applied server-side,
       collapsing every instance's own raw counter into one number
       BEFORE any reset-detection ever ran - so one instance quietly
       restarting (its own raw counter dropping) was completely masked
       whenever another instance was still growing at the same time
       (e.g. two instances 100+100 -> 20+220, the first one having
       restarted: the aggregate read as a +40 increase, when the real
       combined increase was at least +140). Prometheus's own
       increase()/rate() are explicitly designed to detect and
       compensate for a reset PER SERIES, and this must happen BEFORE
       aggregating across series, never after - confirmed against
       Prometheus's own documented reset-handling semantics. The query
       below does exactly that: `increase(...)` is applied to each
       underlying series (one per instance) FIRST, and `sum by
       (tenant)` only wraps the already-reset-compensated per-series
       results afterward - not the other way around.
    3. Both bugs above were specific to this script's OWN Python-side
       measurement; the dashboard/alert did their own, separate
       "current minus a pushed day-start snapshot" subtraction against
       demo_ingestion_midnight_snapshot, which could disagree with
       whatever this script itself was internally acting on, and had
       its own version of the same reset-insensitivity (a straight
       subtraction, no compensation at all) - see SINCE_MIDNIGHT_METRIC's
       own comment for how this is now the ONE value both this script's
       enforcement and the dashboard/alert are based on.

    `only_tenant`, when given, scopes the query to one tenant only,
    with its own `elapsed_seconds` - used for a tenant with an active
    demo `--reset-tenant` override (see main()'s own comment), which
    needs its own, shorter since-reset window instead of the shared
    since-midnight one every other tenant uses. Validated against
    _TENANT_ID_RE before being interpolated into the PromQL string -
    every real tenant_id is already asserted to match this same shape
    in scripts/provision.py's update_gateway_tenant_allowlist(), this
    is defense in depth, not the primary guarantee.

    Known precision boundary, not a bug: increase() extrapolates its
    result from whatever samples actually exist inside the window - it
    does not and cannot reconstruct usage from a genuine gap in the
    underlying scrape history (e.g. an ingester down long enough to
    miss several scrapes). This is bounded (Prometheus caps the
    extrapolation at roughly one sample interval past the first/last
    sample actually seen, it does not stretch a short run of samples
    across the whole window), but it means the value returned here is
    an accurate MEASUREMENT, not a mathematically exact one - the live
    verification this NFR-05 rollout still owes (see README) needs to
    state its allowed overshoot margin with this in mind, not assume
    enforcement triggers at exactly 100.000%.
    """
    if only_tenant is not None:
        assert _TENANT_ID_RE.fullmatch(only_tenant), f"unexpected tenant_id shape: {only_tenant!r}"
        matcher = f'{tenant_label}="{only_tenant}"'
    else:
        matcher = f'{tenant_label}=~".+"'
    promql = f"sum by ({tenant_label}) (increase({metric_name}{{{matcher}}}[{elapsed_seconds}s]))"
    return _instant_query(promql, tenant_label)


def push_metrics(rows: list) -> None:
    """rows: list of (metric_name, extra_labels_dict, value) tuples."""
    now_ms = int(time.time() * 1000)
    series = []
    for metric_name, extra_labels, value in rows:
        labels = [("__name__", metric_name)] + list(extra_labels.items())
        series.append((labels, [(value, now_ms)]))

    payload = _encode_write_request(series)
    compressed = _snappy_compress(payload)
    req = urllib.request.Request(
        MIMIR_PUSH_URL,
        data=compressed,
        method="POST",
        headers={
            "Content-Type": "application/x-protobuf",
            "Content-Encoding": "snappy",
            "X-Prometheus-Remote-Write-Version": "0.1.0",
            "X-Scope-OrgID": ANONYMOUS_ORG_ID,
        },
    )
    with urllib.request.urlopen(req, timeout=15) as resp:
        resp.read()


# --- Kubernetes API access (in-cluster ServiceAccount) - stdlib only ---

_SA_DIR = "/var/run/secrets/kubernetes.io/serviceaccount"


def _k8s_context():
    host = os.environ["KUBERNETES_SERVICE_HOST"]
    port = os.environ["KUBERNETES_SERVICE_PORT"]
    with open(f"{_SA_DIR}/token") as f:
        token = f.read().strip()
    with open(f"{_SA_DIR}/namespace") as f:
        namespace = f.read().strip()
    ctx = ssl.create_default_context(cafile=f"{_SA_DIR}/ca.crt")
    return f"https://{host}:{port}", token, namespace, ctx


def _k8s_request(method, path, body=None, content_type="application/json"):
    base, token, namespace, ctx = _k8s_context()
    url = f"{base}/api/v1/namespaces/{namespace}/{path}"
    data = json.dumps(body).encode("utf-8") if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Authorization", f"Bearer {token}")
    if data is not None:
        req.add_header("Content-Type", content_type)
    try:
        with urllib.request.urlopen(req, timeout=15, context=ctx) as resp:
            return json.load(resp)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def get_configmap(name: str):
    return _k8s_request("GET", f"configmaps/{name}")


def patch_configmap_data(name: str, data_patch: dict):
    """Returns the PATCHed ConfigMap object, or None if it returned 404
    (the ConfigMap no longer exists - e.g. deleted between an earlier
    GET and this PATCH). NFR-05 third pre-test audit round point 2:
    this used to be declared `-> None` and its result was never even
    looked at - a 404 here was caught by _k8s_request() and quietly
    turned into a None return, which every caller then ignored
    entirely, treating "PATCH silently did nothing" as indistinguishable
    from success. Every caller MUST check this return value now."""
    return _k8s_request(
        "PATCH",
        f"configmaps/{name}",
        body={"data": data_patch},
        content_type="application/merge-patch+json",
    )


# --- Targeted per-tenant YAML block patcher ---
#
# All four runtime ConfigMaps this script writes to are generated by
# this repo's own scripts/provision.py with a fixed, consistent shape:
# a top-level "overrides:" (or "runtimeConfig: overrides:") map, one
# nested block per tenant, itself a flat (or, for Tempo, one-level-
# deeper "ingestion:") map of scalar fields. Because the exact shape is
# self-controlled, a full YAML parser/serializer isn't needed - this
# just finds one tenant's block by indentation and rewrites specific
# "field: number" lines inside it, leaving every other tenant and every
# other field (retention, max_traces_per_user, ...) byte-for-byte
# untouched. Verified live against this cluster's actual ConfigMaps
# before being relied on for enforcement.


def patch_tenant_fields(yaml_text: str, tenant: str, field_values: dict) -> tuple:
    """Returns (new_text, found, missing_fields) - `found` is False if
    `tenant`'s own block doesn't exist in this ConfigMap at all, which
    the caller (set_tenant_signal_throttle()) must treat as a real
    failure to retry, not silently swallow (NFR-05 second round point
    3: this used to only print a warning here, with no way for the
    caller to tell "nothing needed changing" apart from "the write
    never actually happened").

    `missing_fields` (NFR-05 third round point 2) is the subset of
    `field_values` whose own "field: number" line was never actually
    matched inside the tenant's block, even though the block itself was
    found - e.g. the block exists but is missing one of the rate/burst
    fields this call expected to patch (a schema drift, a manual edit,
    ...). This used to be silently invisible: `found=True` alone let
    the caller believe the whole call succeeded even when zero of the
    requested fields were actually replaced (new_text stayed byte-
    identical to text, so patch_configmap_data() was never even
    called) - the caller must now treat a non-empty missing_fields the
    same as found=False, a real failure to retry."""
    tenant_pattern = re.compile(rf'^(\s*)"?{re.escape(tenant)}"?:\s*$')
    lines = yaml_text.splitlines(keepends=True)
    out = []
    in_block = False
    tenant_indent = 0
    found = False
    matched_fields = set()
    for line in lines:
        if not in_block:
            m = tenant_pattern.match(line)
            if m:
                in_block = True
                found = True
                tenant_indent = len(m.group(1))
                out.append(line)
                continue
        else:
            if line.strip() == "":
                out.append(line)
                continue
            indent = len(line) - len(line.lstrip(" "))
            if indent <= tenant_indent:
                in_block = False
            else:
                replaced = None
                for field, new_val in field_values.items():
                    fm = re.match(rf'^(\s*){re.escape(field)}:\s*[0-9.]+\s*$', line)
                    if fm:
                        replaced = f"{fm.group(1)}{field}: {new_val}\n"
                        matched_fields.add(field)
                        break
                out.append(replaced if replaced is not None else line)
                continue
        out.append(line)
    missing_fields = set(field_values) - matched_fields
    return "".join(out), found, missing_fields


def set_tenant_signal_throttle(
    tenant: str, signal: str, throttled: bool, runtime_targets: dict, throttle_targets: dict
) -> bool:
    """
    NFR-05 first round: throttles/restores `tenant` on exactly ONE
    signal's own runtime ConfigMap - was set_tenant_throttle(), which
    iterated every system in runtime_targets and throttled all four
    together, back when there was only one combined daily budget to
    cross. Each signal now has its own budget
    (helm/values/ingestion-daily-budgets.yaml) and is checked/throttled
    independently by main() below, so this only ever touches the one
    system named by `signal`.

    `throttle_targets` (built via build_runtime_targets(THROTTLE_RATE_MB,
    THROTTLE_RATE_MB), same shape as `runtime_targets`) supplies the
    throttled field values - fixes the THROTTLE_VALUE unit bug (see that
    constant's own comment): `configmap`/`key` are identical between the
    two (both built by the same function), only `fields` differs, so
    picking the whole target dict from the right one is enough.

    Returns True only once the change is CONFIRMED (or was already the
    case - no-op is still success) - False on any failure: ConfigMap
    missing, tenant's own block missing from it, one or more of the
    expected rate/burst fields missing from an otherwise-found block
    (NFR-05 third round point 2a), or the PATCH call itself raising OR
    reporting 404 - i.e. actually failing, not just returning without
    exception (NFR-05 third round point 2b: patch_configmap_data()'s
    own return value used to be ignored entirely, so a PATCH that hit a
    ConfigMap deleted between the GET above and this call silently
    reported success). NFR-05 second round point 3: this used to return
    nothing at all, and main()/reset_tenant() marked a tenant
    throttled/restored in their OWN state unconditionally right after
    calling this - even when the underlying write silently never
    happened (e.g. the ConfigMap was temporarily missing), permanently
    exempting that tenant from ever being retried again. Callers now
    only update their own state on a confirmed True, and simply leave
    a failed attempt for the next run to retry (main()'s reconciliation
    loop runs this same comparison on every 2-minute poll, not just
    once at a detected day change).
    """
    target = (throttle_targets if throttled else runtime_targets)[signal]
    verb = "throttle" if throttled else "restore"
    try:
        cm = get_configmap(target["configmap"])
    except Exception as e:  # noqa: BLE001 - deliberate: log, skip, retry on the next 2-minute run
        print(f"ERROR: failed to read {target['configmap']} - could not {verb} {tenant} on {signal}: {e}", file=sys.stderr)
        return False
    if cm is None:
        print(f"ERROR: configmap {target['configmap']} not found - could not {verb} {tenant} on {signal}", file=sys.stderr)
        return False
    text = cm.get("data", {}).get(target["key"], "")
    new_text, found, missing_fields = patch_tenant_fields(text, tenant, target["fields"])
    if not found:
        print(f"ERROR: tenant {tenant!r} not found in {target['configmap']} - could not {verb} on {signal}", file=sys.stderr)
        return False
    if missing_fields:
        print(f"ERROR: {tenant!r} found in {target['configmap']} but field(s) {sorted(missing_fields)} missing from its block - could not {verb} on {signal}", file=sys.stderr)
        return False
    if new_text != text:
        try:
            result = patch_configmap_data(target["configmap"], {target["key"]: new_text})
        except Exception as e:  # noqa: BLE001 - deliberate: log, skip, retry on the next 2-minute run
            print(f"ERROR: failed to patch {target['configmap']} for {tenant}/{signal}: {e}", file=sys.stderr)
            return False
        if result is None:
            print(f"ERROR: PATCH on {target['configmap']} returned 404 (no longer exists) - could not {verb} {tenant} on {signal}", file=sys.stderr)
            return False
        print(f"{'Throttled' if throttled else 'Restored'} {tenant} on {signal}")
    return True


# --- Persisted state (which day, confirmed-throttled tenants, active
# demo reset overrides) - no per-tenant usage bookkeeping anymore, see
# this module's own docstring for why. ---


def load_state() -> dict:
    cm = get_configmap(STATE_CONFIGMAP)
    if cm is None or STATE_KEY not in cm.get("data", {}):
        return {"date": None, "throttled": [], "reset_at": {}}
    return json.loads(cm["data"][STATE_KEY])


def save_state(state: dict) -> None:
    result = patch_configmap_data(STATE_CONFIGMAP, {STATE_KEY: json.dumps(state)})
    if result is None:
        # Same class of bug as set_tenant_signal_throttle() (NFR-05
        # third round point 2b) - a 404 here means this run's confirmed
        # throttle/restore state (and any reset_at overrides) was NOT
        # actually persisted. Nothing further to retry within this run
        # (this is already the last step), but it must not be silent -
        # the next run's load_state() would otherwise start over from
        # an empty/stale state without anyone knowing why.
        print(f"ERROR: PATCH on {STATE_CONFIGMAP} returned 404 - this run's state was NOT persisted", file=sys.stderr)


def load_daily_budgets():
    """Tiny two-level YAML reader for
    helm/values/ingestion-daily-budgets.yaml (tenant: {signal: value},
    one nested block per tenant, plus two reserved top-level
    __generic_..._mb__ scalar keys - see that file's own header) - no
    pyyaml dependency needed for a file this simple/self-controlled
    (generated only by scripts/provision.py). A 0-indent "key:" line
    with nothing after the colon opens a tenant's block; a 0-indent
    "key: value" line is a reserved generic scalar; anything indented
    under an open tenant block is one of its signal budgets. Returns
    (budgets: {tenant: {signal: value}}, generic_rate_mb, generic_burst_mb)."""
    budgets = {}
    generic_rate_mb = None
    generic_burst_mb = None
    current_tenant = None
    with open(DAILY_BUDGETS_PATH) as f:
        for raw_line in f:
            line = raw_line.split("#", 1)[0].rstrip("\n")
            stripped = line.strip()
            if not stripped or stripped == "---" or ":" not in stripped:
                continue
            indent = len(line) - len(line.lstrip(" "))
            key, _, val = stripped.partition(":")
            key = key.strip().strip('"')
            val = val.strip()
            if indent == 0:
                if val == "":
                    current_tenant = key
                    budgets[current_tenant] = {}
                elif key == "__generic_rate_mb__":
                    generic_rate_mb = int(val)
                elif key == "__generic_burst_mb__":
                    generic_burst_mb = int(val)
                else:
                    current_tenant = None
            elif current_tenant is not None and val.isdigit():
                budgets[current_tenant][key] = int(val)
    return budgets, generic_rate_mb, generic_burst_mb


def reset_tenant(tenant: str, runtime_targets: dict, throttle_targets: dict) -> None:
    """One-off demo helper (see .gitlab-ci.yml's demo:uc4-fix): un-throttles
    `tenant` on every signal it's currently throttled on and resets its
    daily usage back to 0% on every signal right now, without waiting
    for the next real midnight rollover, and without touching any other
    tenant's state. `throttled` entries are "<tenant>:<signal>" pairs
    (NFR-05 first round: each signal is throttled independently now, see
    set_tenant_signal_throttle()).

    NFR-05 second round: since-midnight usage is no longer script-side
    state at all (main()'s query_since_midnight() computes it fresh
    from Mimir every run, from the real underlying counters) - there is
    nothing left to zero out directly the way the old snapshot/
    accumulator state could be overwritten. Instead this records
    `reset_at[tenant]` (a timestamp), and main() queries that tenant's
    own since-midnight usage from THAT timestamp instead of real
    midnight for the rest of the day - genuinely 0% right after this
    call, then growing again from a real, live-measured 0 exactly like
    every other tenant's own since-midnight usage does, just with a
    later start. Un-throttle attempts that fail are kept in `throttled`
    so main()'s own reconciliation loop retries them on its very next
    run - not lost the way an unconditional state overwrite would lose
    them (NFR-05 second round point 3)."""
    state = load_state()
    throttled = state.get("throttled", [])
    still_throttled = []
    unthrottled_any = False
    for key in throttled:
        key_tenant, _, signal = key.partition(":")
        if key_tenant == tenant:
            if set_tenant_signal_throttle(tenant, signal, throttled=False, runtime_targets=runtime_targets, throttle_targets=throttle_targets):
                unthrottled_any = True
            else:
                still_throttled.append(key)
                print(f"WARNING: could not confirm un-throttle for {tenant}/{signal} - left throttled, next run will retry", file=sys.stderr)
        else:
            still_throttled.append(key)
    state["throttled"] = still_throttled
    if unthrottled_any:
        print(f"Un-throttled {tenant}")
    else:
        print(f"{tenant} was not throttled")

    state.setdefault("reset_at", {})[tenant] = datetime.datetime.now(TZ).timestamp()
    save_state(state)
    print(f"Reset {tenant}'s daily usage to 0% of today's budget on every signal.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--reset-tenant",
        metavar="TENANT_ID",
        help="one-off demo helper (see .gitlab-ci.yml's demo:uc4-fix): un-throttles this "
        "tenant if throttled and resets its daily usage to 0%% on every signal right now, "
        "without waiting for the next real midnight rollover or touching any other "
        "tenant. Exits immediately after, skipping the normal enforcement cycle below.",
    )
    args = parser.parse_args()

    if not os.path.exists(DAILY_BUDGETS_PATH):
        # Fresh build before the first tenants:rollout: the budgets
        # ConfigMap (terraform/environments/tenants) is mounted as
        # optional and does not exist yet - nothing to enforce. Loud on
        # purpose: outside that window it means budgets are NOT being
        # enforced (e.g. observability-stack deployed without a
        # tenants:rollout), which must not look like a healthy run.
        print(
            f"WARNING: {DAILY_BUDGETS_PATH} not found - tenant budgets are not provisioned "
            "(run tenants:rollout), skipping enforcement this run",
            file=sys.stderr,
        )
        return
    budgets, generic_rate_mb, generic_burst_mb = load_daily_budgets()
    runtime_targets = build_runtime_targets(generic_rate_mb, generic_burst_mb)
    throttle_targets = build_runtime_targets(THROTTLE_RATE_MB, THROTTLE_RATE_MB)

    if args.reset_tenant:
        reset_tenant(args.reset_tenant, runtime_targets, throttle_targets)
        return

    state = load_state()
    now = datetime.datetime.now(TZ)
    today = now.date().isoformat()
    if state.get("date") != today:
        # A new day needs no special "restore everyone" step of its own
        # (NFR-05 second round point 3's fix, below, already does this
        # generically) - `throttled` just carries over as the
        # reconciliation loop's own starting point, and since every
        # tenant's since-midnight usage is about to be computed fresh
        # against TODAY's real midnight (tiny elapsed time, so ~0 usage
        # for anyone not already flooding again), the loop below will
        # naturally see they're no longer over budget and restore them
        # on this very run - and retry automatically on the next one if
        # that fails. Demo `reset_at` overrides don't carry into a new
        # day.
        state = {"date": today, "throttled": state.get("throttled", []), "reset_at": {}}
    reset_at = state.setdefault("reset_at", {})

    midnight = datetime.datetime.combine(now.date(), datetime.time.min, tzinfo=TZ)
    # Real wall-clock seconds since actual local midnight, computed
    # fresh every run - NOT "since this script first happened to poll
    # today" (see query_since_midnight()'s own comment for why that
    # distinction is exactly what fixes a late first daily run silently
    # losing real usage). Floored at 60s so a query right at midnight
    # itself still has a valid, non-degenerate range to evaluate.
    # Via timestamps (F16): subtracting two datetimes that share the same
    # ZoneInfo is wall-clock arithmetic and ignores the offset change, so
    # on a DST day it was off by one hour.
    default_elapsed = max(60, int(now.timestamp() - midnight.timestamp()))

    push_rows = []
    since_by_key = {}
    # NFR-05 third round point 1: which signals actually returned a
    # usable measurement this run - a query that raises, or a signal
    # missing from reset_at's own override query, means "we don't know
    # this signal's usage this run", never "usage is 0". Tracked
    # separately from since_by_key itself (which only ever holds real
    # measured values) so the reconciliation loop below can tell "not
    # over budget" apart from "not measured at all" for every tenant on
    # that signal, not just ones that already had a prior measurement.
    measured_signals = set()
    for signal, (metric_name, tenant_label) in SOURCE_METRICS.items():
        try:
            values = query_since_midnight(metric_name, tenant_label, default_elapsed)
        except Exception as e:  # noqa: BLE001 - deliberate: log, skip, retry on the next 2-minute run
            print(f"ERROR: failed to query since-midnight usage for {signal}: {e} - skipping this signal this run, no throttle/restore decisions made for it", file=sys.stderr)
            continue
        measured_signals.add(signal)
        for tenant, reset_ts in reset_at.items():
            # Active demo --reset-tenant override: this tenant's own
            # since-midnight window starts at its own reset time, not
            # real midnight - queried separately since every other
            # tenant still shares the one default_elapsed window above.
            since_reset = max(60, int(now.timestamp() - reset_ts))
            try:
                override = query_since_midnight(metric_name, tenant_label, since_reset, only_tenant=tenant)
            except Exception as e:  # noqa: BLE001 - deliberate: log, skip, retry on the next 2-minute run
                print(f"ERROR: failed to query reset-override usage for {tenant}/{signal}: {e} - no valid measurement for this tenant/signal this run", file=sys.stderr)
                values.pop(tenant, None)
                continue
            if tenant in override:
                values[tenant] = override[tenant]
            else:
                # NFR-05 fourth round: this used to be
                # `values[tenant] = override.get(tenant, 0.0)` -
                # reproduced live that an empty override result (same
                # class of data gap as the non-override path already
                # fixed) was silently treated as "measured exactly 0",
                # which could restore an active throttle on nothing
                # more than a query gap. `tenant not in override` means
                # no data at all in the since-reset window (a real gap,
                # or genuinely too little traffic/too short a window
                # yet for increase() to return anything) - never
                # fabricate a 0.0 for it. The tenant's own DEFAULT
                # (since real midnight) value already sitting in
                # `values` from the query above this loop is not a
                # valid fallback either - it ignores this tenant's own
                # active reset entirely, so using it would defeat the
                # reset's whole purpose. Popped out of `values`
                # entirely instead, so it correctly falls out of
                # since_by_key below - the reconciliation loop already
                # knows not to act on a tenant/signal that wasn't
                # measured this run.
                values.pop(tenant, None)
        for tenant, since in values.items():
            since_by_key[(tenant, signal)] = since
            push_rows.append((SINCE_MIDNIGHT_METRIC, {"signal": signal, "tenant": tenant}, since))
            budget = budgets.get(tenant, {}).get(signal)
            if budget is not None:
                push_rows.append((BUDGET_METRIC, {"tenant": tenant, "signal": signal}, float(budget)))

    # F17: a failed push only costs this run's dashboard samples - it must
    # never stop the throttle/restore decisions below.
    if push_rows:
        try:
            push_metrics(push_rows)
            print(f"Pushed {len(push_rows)} sample(s) ({len(since_by_key)} tenant/signal pair(s) with usage).")
        except Exception as e:  # noqa: BLE001 - deliberate: log and keep enforcing
            print(f"ERROR: failed to push usage metrics: {e} - continuing with enforcement", file=sys.stderr)

    # NFR-05 second round point 3: a plain reconciliation between "what
    # SHOULD be throttled right now" (computed fresh from since_by_key
    # every run) and "what this script's own state says IS confirmed
    # throttled" - run on EVERY poll, not just once at a detected day
    # change. This is what makes both directions (newly-over-budget ->
    # throttle, no-longer-over-budget -> restore) retry automatically:
    # a key only ever leaves `confirmed` (or gets added to it) once
    # set_tenant_signal_throttle() reports the underlying ConfigMap
    # write actually succeeded - a failed attempt just stays exactly
    # where it was and gets retried on the very next run.
    confirmed = set(state.get("throttled", []))
    should_be_throttled = set()
    for (tenant, signal), since in since_by_key.items():
        budget = budgets.get(tenant, {}).get(signal)
        if budget and since >= budget:
            should_be_throttled.add(f"{tenant}:{signal}")

    # Every over-budget key, not only newly crossed ones: a Helm upgrade
    # of the LGTM releases (tenants:rollout, or an observability-stack
    # apply) rewrites the runtime ConfigMaps with the normal limits,
    # silently lifting a throttle this state still records as
    # confirmed. set_tenant_signal_throttle() only writes when the live
    # value differs, so re-asserting is a cheap read on the normal path.
    for key in sorted(should_be_throttled):
        tenant, _, signal = key.partition(":")
        budget = budgets[tenant][signal]
        since = since_by_key[(tenant, signal)]
        unit = "samples" if signal == "mimir" else "bytes"
        if key not in confirmed:
            print(f"{tenant}/{signal}: {since:.0f}/{budget} {unit} today - crossed 100%, throttling")
        if set_tenant_signal_throttle(tenant, signal, throttled=True, runtime_targets=runtime_targets, throttle_targets=throttle_targets):
            confirmed.add(key)
        else:
            print(f"ERROR: could not confirm throttle for {key} - will retry next run", file=sys.stderr)

    # NFR-05 third round point 1, the actual fix: only ever restore a
    # key we ACTUALLY measured this run (present in since_by_key, on a
    # signal that WAS successfully queried) and found genuinely under
    # budget. A key that's confirmed-throttled but missing from this
    # run's measurements (an empty/partial Mimir result, or the whole
    # signal's query having failed above) is left exactly as-is - no
    # action, loudly logged - never silently treated as "0% usage,
    # restore it". Reproduced live: an empty query result previously
    # fell out of since_by_key entirely, which made it vanish from
    # should_be_throttled too, and the reconciliation loop read that
    # absence as "no longer over budget" and lifted a real, active
    # throttle on nothing more than a measurement gap.
    for key in sorted(confirmed):
        tenant, _, signal = key.partition(":")
        if signal not in measured_signals or (tenant, signal) not in since_by_key:
            print(f"WARNING: no measurement for {key} this run - keeping it throttled, not auto-restoring on a data gap", file=sys.stderr)
            # Still re-assert it (no write if already in place): a Helm
            # upgrade may have reset the limit during the data gap.
            if not set_tenant_signal_throttle(tenant, signal, throttled=True, runtime_targets=runtime_targets, throttle_targets=throttle_targets):
                print(f"ERROR: could not re-assert throttle for {key} - will retry next run", file=sys.stderr)
            continue
        if key in should_be_throttled:
            continue  # measured, still genuinely over budget - stays throttled
        if set_tenant_signal_throttle(tenant, signal, throttled=False, runtime_targets=runtime_targets, throttle_targets=throttle_targets):
            confirmed.discard(key)
        else:
            print(f"ERROR: could not confirm restore for {key} - will retry next run", file=sys.stderr)

    state["throttled"] = sorted(confirmed)
    save_state(state)


if __name__ == "__main__":
    main()
