#!/usr/bin/env python3
"""
Ingestion budget enforcer - runs every 2 minutes (formerly once daily,
see git history) as the `ingestion-midnight-snapshot` CronJob
(terraform/environments/observability-stack/main.tf). Two jobs in one:

1. Computes each onboarded tenant's real ingested volume since local
   midnight, per signal (Mimir/Loki/Tempo/Pyroscope), and pushes it as
   a gauge, `demo_ingestion_since_midnight{signal=..., tenant=...}`, so
   the shared alert/dashboard (alerting/shared/operator-ingestion-
   budget.yaml, dashboards/shared/operator-tenant-budget.json, and
   every per-tenant dashboard template) can read it directly as a
   straight percentage of budget - no subtraction on their end at all,
   see query_since_midnight()'s own comment for how this value itself
   is computed (a second NFR-05 pre-test audit round found the
   FIRST-round fix, a hand-rolled Python day-start-snapshot delta, had
   three further confirmed bugs of its own - superseded entirely by
   this version, see query_since_midnight()'s comment for what changed
   and why). Re-pushing the same values every 2 minutes (rather than
   once, at midnight, and never again) is also what fixes a real bug
   found live: a one-off gauge push goes stale
   after Prometheus's default 5-minute staleness window with nothing to
   refresh it.
2. Enforces each tenant's daily ingestion budget (helm/values/
   ingestion-daily-budgets.yaml, size-tier derived - see
   scripts/provision.py's compute_overrides()) by throttling that
   specific tenant's rate/burst limit down to near-zero on the ONE
   signal's live runtime ConfigMap whose own budget it crossed, until
   its own since-midnight usage drops back under budget (normally only
   at the next real midnight, since usage only grows - see main()'s own
   comment for the reconciliation loop this now runs every 2 minutes,
   not just once at a detected day change) - each signal (Mimir/Loki/
   Tempo/Pyroscope) has its own independent budget and is throttled
   independently; crossing Loki's budget no longer also throttles that
   tenant's Tempo/Pyroscope/Mimir traffic (NFR-05 first-round point 1:
   previously one blended budget summed across all four signals, mixing
   Loki/Tempo's real uncompressed bytes, Pyroscope's real but
   COMPRESSED bytes, and Mimir's pure sample-count estimate as if they
   were one unit - see scripts/provision.py's SIZE_MIMIR_SAMPLES_PER_DAY
   comment for the full reasoning). This is deliberately separate from
   the generic, size-independent per-second rate/burst limit every
   tenant gets from onboarding (also computed by compute_overrides(),
   see that function's own comment for why the two are decoupled) -
   that generic limit only protects the platform from being overwhelmed
   *right now*; this script is what actually caps a tenant's *daily*
   usage, per signal. Every throttle/restore attempt's actual success is
   confirmed before updating this script's own state (NFR-05 second
   round: previously a tenant could be marked throttled/restored in
   state even when the underlying ConfigMap write never actually
   happened, permanently skipping any retry - see
   set_tenant_signal_throttle()'s own comment) - a failed attempt is
   retried on every subsequent 2-minute run until it succeeds.

State (which day it is, which tenant/signal pairs are CONFIRMED
currently throttled, and any active demo `--reset-tenant` overrides) is
persisted across runs in the `ingestion-midnight-snapshot-state`
ConfigMap, read/written via the Kubernetes API using the pod's own
ServiceAccount token - stdlib `urllib` only, no `kubernetes` client
library dependency. Unlike the first NFR-05 round, there is no more
per-tenant usage bookkeeping in this state at all - since-midnight
usage is now computed fresh from Mimir on every single run (see
query_since_midnight()), not accumulated/carried across runs by this
script itself.

Deliberately stdlib-only throughout (no `requests`, no `python-snappy`,
no `pyyaml`) - a CronJob's container image shouldn't need a pip install
step on every 2-minute run. The Prometheus remote_write protobuf/Snappy
encoding and the tiny per-tenant YAML block patcher below are simple
enough to hand-roll for the exact, self-controlled file shapes involved
(all of them generated by this same repo's own scripts/provision.py) -
both were prototyped and verified live against this cluster before
being written here. Per-tenant runtime-config overrides are Mimir's own
documented, standard mechanism for tenant-specific limits (not a
workaround) - this script only automates writing to them.

If this doesn't run for a while (cluster down, several missed runs),
enforcement is simply delayed until the next successful run - no
retry/backfill logic for THAT (a missed poll) on purpose (see this
repo's own README on this kind of tradeoff for a demo); a FAILED
throttle/restore ConfigMap write within a run that DID happen, on the
other hand, is retried on every subsequent run until it succeeds (see
point 2 above) - those are different failure modes.
"""
