#!/usr/bin/env python3
"""
Generates the Mimir ruler rule files under rules/ (loaded per tenant by
scripts/sync-mimir-rules.py in tenants:rollout):

  rules/<tenant>/slo.yaml         G03 (FR-10) - from slo/<tenant>/*.yaml
  rules/<tenant>/status.yaml      G08 (FR-08) - every onboarded tenant
  rules/anonymous/business-services.yaml
                                  G08 - from services/business-services.yaml

slo.yaml: the SLO sources are OpenSLO v1. Sloth (pinned in
ci/images/Dockerfile) only reads OpenSLO v1alpha, so each SLO is
converted first (ratioMetric -> ratioMetrics, timeWindow -> timeWindows),
then Sloth generates the recording rules. Sloth creates no alerts from
OpenSLO input, so the multiwindow, multi-burn-rate alerts (Google SRE
workbook: page 14.4x over 1h/5m and 6x over 6h/30m, ticket 3x over
1d/2h and 1x over 3d/6h) and a no-data alert are added here.
Missing data is never counted as success (FR-10): it fires SLONoData,
puts the system into status "unknown" and lowers
slo:data_coverage:ratio_30d, shown on the SLO dashboard.

status.yaml: system:status:code per tenant - 0 functional, 1 degraded
(slow SLO burn), 2 unknown (no telemetry for 10 minutes), 3 disrupted
(fast SLO burn). Higher = worse, so max() across systems is the worst
state; unknown ranks above degraded on purpose - a system we can't see
must not make a service look healthier than one that is merely slow.

Hand-written rule files (no GENERATED banner, e.g. rules/4721-prod/
baseline.yaml, G04) live next to the generated ones and are never
touched here.

Offboarding: rules/<tenant>/ and slo/<tenant>/ of a tenant that is no
longer onboarded are deleted as a whole (hand-written files included -
they belong to the system that is gone).

Usage:
  scripts/generate-rules.py           write rules/
  scripts/generate-rules.py --check   exit 1 if rules/ is out of date
  scripts/generate-rules.py --no-slo  keep the existing slo.yaml files
      (no Sloth needed) - used by scripts/provisioning_sync.py in the
      self-service jobs, which never change slo/; the validate:rules CI
      job checks the SLO part on every MR that does.
Sloth: the `sloth` binary on PATH (CI image), else $SLOTH, else the
pinned image via docker (local runs).
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = REPO_ROOT / "rules"
SLO_DIR = REPO_ROOT / "slo"
SERVICES_FILE = REPO_ROOT / "services" / "business-services.yaml"
SLOTH_IMAGE = "ghcr.io/slok/sloth:v0.16.0"  # keep in sync with ci/images/Dockerfile
BANNER = "# GENERATED by scripts/generate-rules.py - do not edit, regenerate instead."
GENERATED_NAMES = {"slo.yaml", "status.yaml", "business-services.yaml"}

STATUS_FUNCTIONAL, STATUS_DEGRADED, STATUS_UNKNOWN, STATUS_DISRUPTED = 0, 1, 2, 3

# (severity, [(long window, short window, burn-rate factor), ...])
BURN_ALERTS = {
    "page": [("1h", "5m", 14.4), ("6h", "30m", 6)],
    "ticket": [("1d", "2h", 3), ("3d", "6h", 1)],
}


def load_manifests():
    manifests = []
    for path in sorted((REPO_ROOT / "manifests").glob("*/*.yaml")):
        manifests.append(yaml.safe_load(path.read_text()))
    return manifests


def tenants_of(manifests):
    out = []
    for m in manifests:
        for e in m["environments"]:
            out.append({"tenant_id": f"{m['system_id']}-{e['env']}", "system_id": m["system_id"], "env": e["env"], "name": m["name"]})
    return sorted(out, key=lambda t: t["tenant_id"])


# --- G03: SLOs ---


def to_v1alpha(slo: dict) -> dict:
    """OpenSLO v1 SLO (inline ratioMetric indicator) -> v1alpha, the only
    OpenSLO version Sloth reads."""
    if slo.get("apiVersion") != "openslo/v1" or slo.get("kind") != "SLO":
        raise ValueError(f"{slo.get('metadata', {}).get('name')}: expected apiVersion openslo/v1, kind SLO")
    spec = slo["spec"]
    ratio = spec["indicator"]["spec"]["ratioMetric"]

    def query(side):
        source = ratio[side]["metricSource"]
        if source["type"] != "Prometheus":
            raise ValueError(f"{slo['metadata']['name']}: only Prometheus metric sources are supported")
        return {"source": "prometheus", "queryType": "promql", "query": source["spec"]["query"]}

    windows = []
    for w in spec["timeWindow"]:
        duration = w["duration"]
        if not duration.endswith("d"):
            raise ValueError(f"{slo['metadata']['name']}: timeWindow duration must be in days, got {duration}")
        windows.append({"count": int(duration[:-1]), "unit": "Day", "isRolling": w.get("isRolling", True)})

    return {
        "apiVersion": "openslo/v1alpha",
        "kind": "SLO",
        "metadata": {"name": slo["metadata"]["name"], "displayName": slo["metadata"].get("displayName", slo["metadata"]["name"])},
        "spec": {
            "service": spec["service"],
            "description": spec.get("description", ""),
            "budgetingMethod": spec.get("budgetingMethod", "Occurrences"),
            "objectives": [
                {
                    "displayName": o.get("displayName", ""),
                    "target": o["target"],
                    "ratioMetrics": {"counter": ratio.get("counter", True), "good": query("good"), "total": query("total")},
                }
                for o in spec["objectives"]
            ],
            "timeWindows": windows,
        },
    }


def run_sloth(src: Path, sloth_arg: str | None) -> str:
    sloth = sloth_arg or shutil.which("sloth")
    if sloth:
        cmd = [sloth, "generate", "--no-log", "-i", str(src)]
    elif shutil.which("docker"):
        cmd = ["docker", "run", "--rm", "-v", f"{src.parent}:/in:ro", SLOTH_IMAGE, "generate", "--no-log", "-i", f"/in/{src.name}"]
    else:
        sys.exit("sloth not found (PATH, $SLOTH or docker)")
    result = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        sys.exit(f"sloth failed for {src.name}:\n{result.stderr}")
    return result.stdout


def burn_condition(long_w: str, short_w: str, factor: float) -> str:
    def over(window):
        return (
            f"max by (sloth_id, sloth_service, sloth_slo) (slo:sli_error:ratio_rate{window})"
            f" > on(sloth_id) group_left() ({factor} * max by (sloth_id) (slo:error_budget:ratio))"
        )

    return f"({over(long_w)} and on(sloth_id) {over(short_w)})"


def slo_alert_groups(tenant_id: str) -> list:
    rules = []
    for severity, windows in BURN_ALERTS.items():
        rules.append({
            "record": f"slo:burn_alert:{severity}",
            "expr": " or ".join(burn_condition(*w) for w in windows),
        })
    rules += [
        {
            # FR-10: share of the 30-day window with SLI data at all (1m
            # evaluation interval -> 43200 samples in 30 days).
            # slo:sli_data:present: rules/<tenant>/status.yaml.
            "record": "slo:data_coverage:ratio_30d",
            "expr": "count_over_time(slo:sli_data:present[30d]) / 43200",
        },
        {
            "alert": "SLOFastBurn",
            "expr": "slo:burn_alert:page",
            "labels": {"severity": "critical", "tenant": tenant_id},
            "annotations": {
                "summary": "SLO {{ $labels.sloth_slo }} of {{ $labels.sloth_service }} burns its error budget fast",
                "description": "At this rate the 30-day error budget is gone within about 2 days (14.4x over 1h and 5m, or 6x over 6h and 30m).",
            },
        },
        {
            "alert": "SLOSlowBurn",
            "expr": "slo:burn_alert:ticket",
            "labels": {"severity": "warning", "tenant": tenant_id},
            "annotations": {
                "summary": "SLO {{ $labels.sloth_slo }} of {{ $labels.sloth_service }} burns its error budget faster than planned",
                "description": "3x over 1d and 2h, or 1x over 3d and 6h - the budget runs out before the end of the 30-day window.",
            },
        },
        {
            "alert": "SLONoData",
            "expr": "sloth_slo_info unless on(sloth_id) slo:sli_data:present",
            "for": "15m",
            "labels": {"severity": "warning", "tenant": tenant_id},
            "annotations": {
                "summary": "SLO {{ $labels.sloth_slo }} of {{ $labels.sloth_service }} has no SLI data",
                "description": "The SLI query returns nothing (no traffic, telemetry missing or the tenant's ingestion budget throttled). This time does not count as success: it is missing from slo:data_coverage:ratio_30d and the system's status is unknown.",
            },
        },
    ]
    return [{"name": "slo-burn-rate-alerts", "rules": rules}]


def generate_slo_rules(tenant_id: str, sloth: str | None, no_slo: bool = False) -> dict | str | None:
    sources = sorted((SLO_DIR / tenant_id).glob("*.yaml"))
    if not sources:
        return None
    if no_slo:
        existing = RULES_DIR / tenant_id / "slo.yaml"
        if not existing.exists():
            sys.exit(f"--no-slo: slo/{tenant_id}/ has SLOs but rules/{tenant_id}/slo.yaml is missing - run without --no-slo")
        return existing.read_text()
    groups = []
    with tempfile.TemporaryDirectory() as tmp:
        for src in sources:
            converted = Path(tmp) / src.name
            converted.write_text(yaml.safe_dump(to_v1alpha(yaml.safe_load(src.read_text())), sort_keys=False))
            # Readable for the Sloth image's non-root user (docker mode).
            Path(tmp).chmod(0o755)
            converted.chmod(0o644)
            groups += yaml.safe_load(run_sloth(converted, sloth))["groups"]
    for g in groups:
        g.setdefault("interval", "1m")
    return {"groups": groups + slo_alert_groups(tenant_id)}


# --- G08: status model ---


def status_rules(tenant: dict, has_slos: bool) -> dict:
    labels = {"system_id": tenant["system_id"], "env": tenant["env"], "tenant": tenant["tenant_id"], "system_name": tenant["name"]}
    # Worst state over all SLOs: fast burn > no SLI data > slow burn. An
    # SLO without SLI data (its spans missing while other telemetry still
    # arrives) is "unknown", not "functional". Each term gets its own
    # "term" label, so `or` never drops one for having equal labels.
    worst_slo = (
        "max("
        f'label_replace(slo:burn_alert:page * 0 + {STATUS_DISRUPTED}, "term", "page", "", "")'
        f' or label_replace(slo:burn_alert:ticket * 0 + {STATUS_DEGRADED}, "term", "ticket", "", "")'
        f' or label_replace((sloth_slo_info unless on(sloth_id) slo:sli_data:present) * 0 + {STATUS_UNKNOWN}, "term", "nodata", "", "")'
        f") or vector({STATUS_FUNCTIONAL})"
        if has_slos
        else f"vector({STATUS_FUNCTIONAL})"
    )
    # 1 per SLO whose 5m SLI is a number. Zero traffic (counters present
    # but flat) gives 0/0 = NaN - no evidence either way, so it counts as
    # "no data" (SLONoData, coverage, status unknown) like a missing SLI.
    # NaN == NaN is false, so the self-comparison drops exactly those.
    sli_present = [{
        "record": "slo:sli_data:present",
        "expr": "(slo:sli_error:ratio_rate5m == slo:sli_error:ratio_rate5m) * 0 + 1",
    }] if has_slos else []
    return {
        "groups": [{
            "name": "status-model",
            "interval": "1m",
            "rules": [
                {"record": "system:telemetry:present", "expr": "(count(last_over_time(target_info[10m])) > bool 0) or vector(0)"},
                *sli_present,
                {"record": "system:slo:worst_status", "expr": worst_slo},
                {
                    "record": "system:status:code",
                    "expr": f"(vector({STATUS_UNKNOWN}) and on() (system:telemetry:present == 0)) or on() system:slo:worst_status",
                    "labels": labels,
                },
            ],
        }]
    }


def business_service_rules(tenants, manifests, strict: bool = True) -> dict:
    services = yaml.safe_load(SERVICES_FILE.read_text())["services"]
    known = {str(m["system_id"]) for m in manifests}
    rules = [{
        # Per-system status, copied into this operator tenant for the
        # status dashboard (dashboards/shared/operator-service-status.json).
        "record": "operator:system_status:code",
        "expr": "max by (system_id, system_name, env, tenant) (system:status:code)",
    }]
    for svc in services:
        members = [str(s) for s in svc["systems"]]
        unknown = sorted(set(members) - known)
        if unknown:
            # Strict (--check, MR pipelines): a typo or a forgotten entry
            # fails. Self-service (offboarding): drop the member with a
            # warning, so removing a system never blocks on this file.
            msg = f"business service {svc['name']!r}: unknown system_id(s) {unknown} - update {SERVICES_FILE.relative_to(REPO_ROOT)}"
            if strict:
                sys.exit(msg)
            print(f"WARNING: {msg}", file=sys.stderr)
            members = [m for m in members if m in known]
            if not members:
                continue
        selector = f'system:status:code{{system_id=~"{"|".join(members)}", env="{svc.get("env", "prod")}"}}'
        n = len(members)
        rules.append({
            "record": "business_service:status:code",
            # Worst member; a member without any status series (not yet
            # evaluated, tenant gone) makes the service "unknown". The
            # "term" labels keep `or` from dropping the fallback whenever
            # some other member does report.
            "expr": (
                f'max(label_replace(max({selector}), "term", "members", "", "")'
                f' or label_replace(vector({STATUS_UNKNOWN}) unless on() (count({selector}) >= {n}), "term", "missing", "", ""))'
            ),
            "labels": {"service": svc["name"]},
        })
    return {
        "groups": [{
            "name": "business-services",
            "interval": "1m",
            # Mimir tenant federation (ruler.tenant_federation) - the group
            # reads system:status:code from all these tenants.
            "source_tenants": [t["tenant_id"] for t in tenants],
            "rules": rules,
        }]
    }


# --- output ---


class _IndentDumper(yaml.SafeDumper):
    """Indents list items under their key - the repo's yamllint style."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def render(data: dict) -> str:
    return "---\n" + BANNER + "\n" + yaml.dump(data, Dumper=_IndentDumper, sort_keys=False, width=200)


def orphaned_dirs(tenants) -> list[Path]:
    """rules/<tenant>/ and slo/<tenant>/ of tenants no longer onboarded."""
    known = {t["tenant_id"] for t in tenants} | {"anonymous"}
    return [p for base in (RULES_DIR, SLO_DIR) if base.exists() for p in sorted(base.iterdir()) if p.is_dir() and p.name not in known]


def build(sloth: str | None, no_slo: bool = False) -> dict[Path, str]:
    manifests = load_manifests()
    tenants = tenants_of(manifests)
    files = {}
    for t in tenants:
        slo = generate_slo_rules(t["tenant_id"], sloth, no_slo)
        if slo:
            files[RULES_DIR / t["tenant_id"] / "slo.yaml"] = slo if isinstance(slo, str) else render(slo)
        files[RULES_DIR / t["tenant_id"] / "status.yaml"] = render(status_rules(t, slo is not None))
    files[RULES_DIR / "anonymous" / "business-services.yaml"] = render(business_service_rules(tenants, manifests, strict=not no_slo))
    return files


def stale_generated(files: dict[Path, str]) -> list[Path]:
    """Generated files on disk that build() no longer produces."""
    if not RULES_DIR.exists():
        return []
    return [p for p in RULES_DIR.glob("*/*.yaml") if p.name in GENERATED_NAMES and p not in files and p.read_text().startswith("---\n" + BANNER)]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--sloth", default=None)
    parser.add_argument("--no-slo", action="store_true")
    args = parser.parse_args()

    files = build(args.sloth or os.environ.get("SLOTH"), args.no_slo)
    stale = stale_generated(files)
    orphans = orphaned_dirs(tenants_of(load_manifests()))
    if args.check:
        bad = [p for p, c in files.items() if not p.exists() or p.read_text() != c] + stale + orphans
        for p in bad:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        if bad:
            print("run scripts/generate-rules.py and commit the result")
            return 1
        print(f"rules/ up to date ({len(files)} generated files)")
        return 0
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c)
    for p in stale:
        p.unlink()
    for d in orphans:
        shutil.rmtree(d)
        print(f"removed {d.relative_to(REPO_ROOT)}/ (tenant no longer onboarded)")
    print(f"wrote {len(files)} files, removed {len(stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
